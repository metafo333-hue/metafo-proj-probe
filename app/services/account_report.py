"""综合分析报告生成器 v2 · 确定性(规则驱动·零 LLM·零网络)。

目标:像一份真正给创作者看的诊断报告——说人话、每个数字翻译成普通人能懂的话、有价值感。
结构:重点先说 → 你现在的情况 → 最该解决的问题 → 你的优势 → 怎么做 → 未来 → 可信度。
价值对齐北极星:处方默认"放大你自己的真东西"(非抄袭);黑盒维诚实标;单源诚实。
"""
from __future__ import annotations

from typing import Any

# 赛道关键词 → 赛道名(据 playbook 八大类·轻量可扩展)。值用大白话。
_TRACK_HINTS = [
    (("女性", "妈妈", "职场", "成长", "婚姻", "情感", "她"), "女性成长 / 情感共鸣",
     "这类粉丝精准、信任度高,以后能靠情感陪伴、知识分享变现,适合走「小而美、深耕」的路,不用拼几百万播放"),
    (("育儿", "孩子", "宝妈", "母婴", "亲子"), "母婴育儿",
     "妈妈群体消费力强,适合带货、本地服务、知识付费"),
    (("美食", "探店", "吃", "菜", "厨"), "美食",
     "受众极广,适合探店团购、带货变现"),
    (("健身", "运动", "瑜伽", "减肥"), "健身运动",
     "需求刚性,适合卖课、社群、装备带货"),
    (("考证", "财经", "理财", "知识", "科普", "学习"), "知识科普",
     "单个粉丝很值钱,适合引流到私域卖高客单的课/咨询"),
    (("穿搭", "美妆", "时尚", "护肤"), "时尚美妆",
     "品牌预算最多,适合带货和品牌合作"),
]


def _track(text: str) -> tuple[str, str]:
    for kws, name, why in _TRACK_HINTS:
        if any(k in text for k in kws):
            return name, why
    return "生活记录", "适合慢慢积累信任,后续带货或本地服务变现"


def _stage(fol: int) -> str:
    if fol < 500:
        return f"{fol} 个粉丝、刚起步的小号(大家都从这儿开始,很正常)"
    if fol < 5000:
        return f"{fol} 个粉丝、成长初期"
    if fol < 50000:
        return f"{fol} 个粉丝、有了一定基础"
    return f"{fol} 个粉丝、比较成熟的号"


def build_report(video: dict[str, Any], account: dict[str, Any], audit: dict[str, Any]) -> str:
    nick = account.get("nickname") or "你"
    fol = account.get("follower") or 0
    avg = account.get("avg_like") or 0
    mx = account.get("max_like") or 0
    vert = account.get("vertical_score")
    vert = vert if vert is not None else 0.0
    aweme = account.get("aweme_count") or 0
    sig = (account.get("signature") or "").strip()
    tags = [t for t in (account.get("hashtags") or []) if t]
    title = (video.get("title") or "").strip()
    like = video.get("like") or 0
    comment = video.get("comment") or 0
    share = video.get("share") or 0
    collect = video.get("collect") or 0

    散 = vert < 0.6
    spark = mx > avg * 3 and mx > 0
    track, track_why = _track(" ".join(tags) + sig + title)
    tags_str = "、".join(tags) if tags else "(没识别到明显标签)"
    ratio = like / (avg + 1)
    if ratio > 2:
        this = f"明显高于你平时(你平均 {avg} 个赞),算你的一条小爆款,值得好好复盘"
    elif ratio < 0.5:
        this = f"低于你平时(你平均 {avg} 个赞),这条偏冷"
    else:
        this = f"和你平时差不多(你平均 {avg} 个赞),属于正常发挥——不算失败,也不算爆"
    title_short = (title[:34] + "…") if len(title) > 34 else title

    L: list[str] = []
    P = L.append

    P(f"# 📋 账号诊断报告 · @{nick}")
    P("")
    P("> 这份报告基于你抖音账号的真实公开数据生成。我尽量说人话,你拿着就能照着做。")
    P("")

    # —— 重点先说 ——
    P("## 一句话先说重点")
    if 散:
        P("**你的内容是有价值的,真正的问题不是「做得不好」,而是「方向太杂、系统认不清你是谁」。把方向收窄,你这个号能起来。**")
    else:
        P("**你的方向比较清晰,接下来把已经验证过的内容做深做透就好。**")
    P("")

    # —— 一、现状体检 ——
    P("## 一、你现在是什么情况")
    P("")
    P("**你是谁、在做什么**")
    if sig:
        P(f"你的简介写着:「{sig}」—— 能看出你是个有想法、愿意分享真实人生感悟的人。")
    P(f"你发的内容,大方向是「**{track}**」。")
    P("")
    P("**你现在的水平**")
    P(f"- {_stage(fol)},一共发了 {aweme} 条作品。")
    P(f"- 你的视频平均 **{avg} 个赞**,最好的一条有 **{mx} 个赞**。")
    P("")
    P("**你发的这条视频表现怎么样**")
    if title_short:
        P(f"- 这条讲的是:「{title_short}」")
    P(f"- 数据:{like} 个赞、{comment} 条评论、{share} 次转发、{collect} 个收藏。")
    P(f"- 跟你自己比:**{this}**。" + ("别因为这一条数字焦虑——要看的是整体趋势,不是单独一条。" if ratio < 2 else ""))
    P("")

    # —— 二、最关键问题 ——
    if 散:
        P("## 二、你现在最该解决的一件事:账号「太杂」")
        P("")
        P(f"你最近视频贴的标签是这些:**{tags_str}**。")
        P("")
        P("发现没?**这其实是好几个不同的方向。** 抖音给不给你推流量,全靠它「猜你是做什么的」。你一会儿讲这个、一会儿讲那个,系统就懵了:「这号到底是做什么的?该推给谁?」结果谁也不敢多推。")
        P("")
        P("你的粉丝也一样:关注你的人,不知道下次能从你这儿看到什么,黏性就弱。")
        P("")
        P(f"**这就解释了一个矛盾:你明明有能力做出 {mx} 个赞的内容(说明你会做),但整体一直起不来(因为太散)。问题不在内容好不好,在「聚不聚焦」。**")
    else:
        P("## 二、你做得对的地方")
        P(f"你的内容方向比较集中,系统能认清你是做「{track}」的——这是好事,接着往深里做。")
    P("")

    # —— 三、你的优势 ——
    P("## 三、你有一个别人抢不走的优势")
    P("")
    P("别灰心,你手里有最值钱的东西:**真实**。")
    if title_short:
        P(f"你讲的「{title_short}」这种真实的人生纠结,是你亲身经历、带着体温的东西 —— 这是 AI 编不出来、别的博主也抄不像的。")
    P("现在 AI 生成的内容满天飞,**恰恰是你这种「真实的生活思考」最稀缺、最值钱**。")
    if spark:
        P(f"而且你已经有一条 {mx} 个赞的视频,说明当你戳中真实情绪时,是能打动人的。")
    P("")

    # —— 四、怎么做 ——
    P("## 四、接下来具体怎么做(照着做就行)")
    P("")
    n = 1
    if 散:
        P(f"**第 {n} 步(最重要):把方向收窄到一个**")
        P(f"别再 {len(tags) or '好几'} 个方向都发。挑你最真实、最有话说的那一个 —— 比如你这条讲的「真实的生活/情感纠结」,这个切口就很好:真实、有共鸣、有一大批同样状态的人在找答案。")
        P("> 建议:接下来一个月,只围绕**这一个主题**发。让系统和粉丝一看就知道「她是讲这个的」。")
        P("")
        n += 1
    P(f"**第 {n} 步:把最揪心的那句话,放到开头 3 秒**")
    P("抖音前 3 秒,决定别人划不划走。大多数人把最有冲突、最戳心的话放在了中间 —— 试着一开口就甩出那句最能戳中人的话,别人才会停下来看完。")
    P("")
    n += 1
    if spark:
        P(f"**第 {n} 步:把你自己那条 {mx} 个赞的视频研究透**")
        P(f"你最好的一条为什么能到 {mx} 个赞?翻出来,看它讲了什么、开头怎么说、戳中了什么情绪,然后多做那个方向 —— **这是放大你自己已经验证过的成功,比抄别人靠谱得多**。")
        P("")

    # —— 五、未来 ——
    P("## 五、照这样走,接下来会怎样(说实话,不夸张)")
    P(f"- 你做的「{track}」是个**值钱的方向**:{track_why}。")
    if 散:
        P("- 如果继续这么散,大概率会一直「偶尔一条小爆、整体不温不火」。")
        P("- 但一旦你聚焦、系统认清你了,起量会比现在稳得多 —— 你已经证明了有做好内容的能力,**差的就是这个聚焦**。")
    if spark:
        P("- 你有过小爆款,说明天花板不低;关键是把「偶然」变成「稳定」。")
    P("")

    # —— 六、可信度 ——
    P("## 六、这份分析有多可信(实话实说)")
    P("- 上面的数字(粉丝、点赞、作品、标签)**都是你抖音账号的真实公开数据,没有一个是编的**。")
    P("- 但有两个诚实的提醒:")
    P("  1. 这次**只看了你一个号、一个数据来源**,没跟别处交叉验证,所以给你的是「靠谱的方向」,别当成 100% 精确的结论。")
    P("  2. 有些关键数据抖音**不公开** —— 比如完播率(多少人看完)、流量从哪来、有没有转化 —— 这些拿不到,我**宁可告诉你「拿不到」,也绝不瞎编**。")
    return "\n".join(L)
